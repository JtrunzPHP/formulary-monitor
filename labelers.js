function mapLabeler(labelerName) {
  const name = (labelerName || '').trim();
  if (!name) return { parent: '', ticker: '' };
  for (const p of LABELERS) {
    if (p.match.test(name)) return { parent: p.parent, ticker: p.ticker };
  }
  return { parent: 'UNMAPPED', ticker: '' };
}

